import DOMPurify from "dompurify";

const PURIFY_CONFIG = {
  ALLOWED_TAGS: [
    "p",
    "br",
    "strong",
    "em",
    "a",
    "ul",
    "ol",
    "li",
    "h1",
    "h2",
    "h3",
    "h4",
    "h5",
    "h6",
    "hr",
    "blockquote",
    "table",
    "thead",
    "tbody",
    "tfoot",
    "tr",
    "th",
    "td",
    "code",
    "pre",
    "span",
    "div",
    "button",
    "svg",
    "path",
    "rect",
    "circle",
    "line",
    "polyline",
    "polygon",
  ],
  ALLOWED_ATTR: [
    "class",
    "hidden",
    "role",
    "tabindex",
    "aria-label",
    "aria-hidden",
    "href",
    "target",
    "rel",
    "title",
    "start",
    "width",
    "height",
    "viewBox",
    "fill",
    "stroke",
    "stroke-width",
    "stroke-linecap",
    "stroke-linejoin",
    "d",
    "x",
    "y",
    "rx",
    "ry",
    "type",
  ],
  ALLOW_DATA_ATTR: false,
};

export function sanitizeHTML(dirty: string): string {
  return DOMPurify.sanitize(dirty, PURIFY_CONFIG);
}
